"""回归 Check-All 六项修复，使用本地示例覆盖连续操作与共享状态。"""
import asyncio
import json
from pathlib import Path
from playwright.async_api import async_playwright, expect


async def main():
    """执行六项问题原复现与关联边界。@return 无。"""
    output = Path('.deploy/frontend-sidebar-refresh/concept/check-repairs')
    output.mkdir(parents=True, exist_ok=True)
    errors, network, checks = [], [], []
    async with async_playwright() as playwright:
        browser = await playwright.chromium.launch()
        page = await browser.new_page(viewport={'width': 1440, 'height': 1000})
        page.on('pageerror', lambda error: errors.append(str(error)))
        page.on('request', lambda request: network.append(request.url) if request.url.startswith(('http:', 'https:')) else None)
        url = Path('doc/design/flower2api-concept.html').resolve().as_uri()
        dialog = page.locator('#action-dialog')

        async def reset(hash_value='#tasks'):
            """装载独立示例，清除上个场景的内存状态。@param hash_value 目标路由。@return 无。"""
            await page.goto('about:blank')
            await page.goto(url + hash_value)

        async def authorize():
            """通过显式本地授权码完成当前草稿。@return 无。"""
            await dialog.locator('[name="work_authorization_code"]').fill('demo-code')
            await dialog.get_by_role('button', name='验证授权码', exact=True).click()
            await dialog.locator('[data-work-login-commit]').click()
            await expect(dialog).not_to_be_visible()

        # 删除默认样例后创建，两个空间均从独立默认值初始化。
        await reset()
        await page.locator('[data-work-account-delete="101"]').click()
        await page.locator('dialog[open] [data-work-confirm]').click()
        await page.locator('[data-work-login-resume="1"]').click()
        await authorize()
        await expect(page.locator('[data-work-account-card="104"]')).to_be_visible()
        await page.get_by_role('button', name='添加任务账号', exact=True).click()
        await dialog.locator('[name="name"]').fill('第二个新账号')
        await dialog.get_by_role('button', name='进入授权预览').click()
        await authorize()
        assert await page.evaluate("[104,105].every(id=>['projects','warmup'].every(mode=>{const s=workSpaces.get(mode+':'+id);return s&&s.account_id===id&&!s.controller_active&&!s.project_keys.length&&!s.schedule.enabled&&!s.model.api_key}))&&workLoginDrafts.length===0")
        await page.evaluate("workSpaces.get('projects:104').model.api_key='demo-only';workSpaces.get('projects:104').project_keys.push('tinyhttp')")
        assert await page.evaluate("workSpaces.get('projects:105').model.api_key===''&&workSpaces.get('warmup:104').project_keys.length===0")
        for account_id in [102, 103, 104, 105]:
            await page.locator(f'[data-work-account-delete="{account_id}"]').click()
            await page.locator('dialog[open] [data-work-confirm]').click()
        await page.get_by_role('button', name='添加任务账号', exact=True).click()
        await dialog.locator('[name="name"]').fill('清空后重建')
        await dialog.get_by_role('button', name='进入授权预览').click()
        await authorize()
        assert await page.evaluate("workAccounts.length===1&&workAccounts[0].id===106&&workSpaces.has('projects:106')&&workSpaces.has('warmup:106')&&!workEnvironmentRefs.has(106)")
        checks.append('CHK-001：删除样例后连续创建及空间隔离')

        await reset('#tasks?tab=warmup&account=102')
        await page.locator('[data-work-pane="schedule"]').first.click()
        upper = page.locator('[name="interval_max_minutes"]')
        await upper.fill('')
        assert await upper.evaluate('e=>e.checkValidity()&&!e.required')
        await page.get_by_role('button', name='保存计划', exact=True).click()
        assert await page.evaluate("workSpaces.get('warmup:102').schedule.interval_max_minutes===null")
        await expect(upper).to_have_value('')
        await upper.fill('180')
        await page.get_by_role('button', name='保存计划', exact=True).click()
        assert await page.evaluate("workSpaces.get('warmup:102').schedule.interval_max_minutes===180")
        await upper.fill('179')
        await page.get_by_role('button', name='保存计划', exact=True).click()
        await expect(page.locator('.work-form-error')).to_contain_text('上限不能小于下限')
        assert await page.evaluate("workSpaces.get('warmup:102').schedule.interval_max_minutes===180")
        checks.append('CHK-002：上限空值、相等及非法范围')

        await page.locator('[data-page="settings"]').click()
        assert await page.evaluate("location.hash==='#settings'&&current==='settings'")
        await page.reload()
        assert await page.evaluate("current==='settings'")
        await page.locator('[data-page="proxies"]').click()
        length = await page.evaluate('history.length')
        await page.evaluate("navigate('proxies')")
        assert await page.evaluate('history.length') == length
        await page.go_back()
        assert await page.evaluate("current==='settings'")
        await page.go_back()
        assert await page.evaluate("current==='tasks'&&taskTab==='warmup'&&workView.accountId===102")
        await page.go_forward()
        assert await page.evaluate("current==='settings'")
        checks.append('CHK-003：跨模块刷新、历史及重绘去重')

        await reset()
        await page.locator('[data-work-env="102"]').click()
        await dialog.get_by_role('combobox', name='时区', exact=True).click()
        await page.get_by_role('option', name='America/Los_Angeles · 洛杉矶', exact=True).click()
        await dialog.get_by_role('button', name='保存时段', exact=True).click()
        await page.keyboard.press('Escape')
        await expect(page.locator('[data-work-account-card="102"]')).to_contain_text('America/Los_Angeles')
        await page.evaluate('openWorkLogin(102)')
        await expect(dialog.locator('[name="timezone"]')).to_have_value('America/Los_Angeles')
        await page.keyboard.press('Escape')
        await page.locator('[data-page="environments"]').click()
        await page.evaluate("selected=1;openEnvironmentWorkspace('schedule')")
        await dialog.get_by_role('combobox', name='时区', exact=True).click()
        await page.get_by_role('option', name='Asia/Tokyo · 东京', exact=True).click()
        await dialog.get_by_role('button', name='保存时段', exact=True).click()
        await page.keyboard.press('Escape')
        await page.locator('[data-page="tasks"]').click()
        await expect(page.locator('[data-work-account-card="102"]')).to_contain_text('Asia/Tokyo')
        await page.evaluate('openWorkLogin(102)')
        await expect(dialog.locator('[name="timezone"]')).to_have_value('Asia/Tokyo')
        await dialog.get_by_role('button', name='进入授权预览').click()
        # 授权期间时区变化，提交仍采用当前关联环境的权威值。
        await page.evaluate("environmentDemo.get(1).timezone='Asia/Shanghai'")
        await authorize()
        assert await page.evaluate("workAccounts.find(a=>a.id===102).timezone==='Asia/Shanghai'&&workTimezone(workAccounts.find(a=>a.id===102))==='Asia/Shanghai'")
        checks.append('CHK-004：双入口时区、授权回填与迟到提交')

        await reset('#proxies')
        await page.locator('[data-action="proxy-import"]').click()
        await dialog.locator('[name="urls"]').fill('socks5://demo%40user:p%3Ass@import.example.test:1080\nhttp://demo:secret@[::1]:8080\ninvalid')
        await dialog.get_by_role('button', name='导入代理', exact=True).click()
        await expect(dialog.locator('[data-proxy-import-error]')).to_contain_text('第 3 行')
        assert await page.evaluate('previewProxies.length===3')
        await dialog.locator('[name="urls"]').fill('socks5://demo%40user:p%3Ass@import.example.test:1080\nhttp://demo:secret@[::1]:8080')
        await dialog.get_by_role('button', name='导入代理', exact=True).click()
        assert await page.evaluate("previewProxies[3].username==='demo@user'&&previewProxies[3].password==='p:ss'&&previewProxies[4].username==='demo'&&previewProxies[4].password==='secret'")
        await expect(page.locator('[data-proxy-row="4"]')).not_to_contain_text('demo@user')
        await page.locator('[data-proxy-row="4"] [data-proxy-action="edit"]').click()
        await expect(dialog.locator('[name="username"]')).to_have_value('demo@user')
        await expect(dialog.locator('[name="password"]')).to_have_value('p:ss')
        await page.keyboard.press('Escape')
        checks.append('CHK-005：认证导入、编码/IPv6、非法行原子拒绝及回填')

        await reset()
        await page.locator('[data-work-proxy-switch="103"]').click()
        await dialog.get_by_role('combobox', name='代理线路', exact=True).click()
        await page.get_by_role('option', name='备用线路', exact=True).click()
        await dialog.get_by_role('button', name='保存并切换', exact=True).click()
        await page.locator('[data-page="proxies"]').click()
        row = page.locator('[data-proxy-row="3"]')
        await expect(row).to_contain_text('1 个使用')
        await expect(row).to_contain_text('实验工作区')
        await row.locator('[data-proxy-action="delete"]').click()
        await expect(dialog.locator('[data-proxy-confirm-delete]')).to_have_count(0)
        await page.keyboard.press('Escape')
        await row.locator('[data-proxy-action="accounts"]').click()
        await page.locator('.proxy-expanded [data-proxy-task="103"]').last.click()
        await expect(dialog).to_contain_text('切换代理 · 实验工作区')
        await dialog.get_by_role('combobox', name='代理线路', exact=True).click()
        await page.get_by_role('option', name='直连', exact=True).click()
        await dialog.get_by_role('button', name='保存并切换', exact=True).click()
        await page.locator('[data-page="proxies"]').click()
        # 确认窗口打开后新增草稿引用，提交时再次核验占用。
        await row.locator('[data-proxy-action="delete"]').click()
        await page.evaluate("workLoginDrafts[0].proxyId='3'")
        await dialog.locator('[data-proxy-confirm-delete="3"]').click()
        assert await page.evaluate('previewProxies.some(p=>p.id===3)')
        await page.keyboard.press('Escape')
        await page.evaluate("navigate('proxies')")
        if await row.locator('[data-proxy-action="accounts"]').get_attribute('aria-expanded') == 'false':
            await row.locator('[data-proxy-action="accounts"]').click()
        await expect(page.locator('.proxy-expanded')).to_contain_text('登录草稿')
        await page.locator('.proxy-expanded [data-proxy-draft="1"]').last.click()
        await expect(dialog).to_contain_text('授权登录')
        await page.keyboard.press('Escape')
        await page.locator('[data-work-login-delete="1"]').click()
        await page.locator('dialog[open] [data-work-confirm]').click()
        await page.locator('[data-page="proxies"]').click()
        await row.locator('[data-proxy-action="delete"]').click()
        await dialog.locator('[data-proxy-confirm-delete="3"]').click()
        await expect(row).to_have_count(0)
        assert await page.evaluate('accountsUsingProxy(1).length===accounts.filter(a=>a.proxyId===1).length')
        await page.set_viewport_size({'width': 390, 'height': 900})
        await page.evaluate("proxyAction('accounts',1)")
        assert await page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        await page.screenshot(path=str(output / 'proxy-usage-390.png'), full_page=True)
        checks.append('FBK-001：任务/草稿占用、确认期变化、跳转、释放与绑定去重')
        assert not errors, errors
        assert not network, network
        result = {'status': 'passed', 'checks': checks, 'errors': errors, 'network': network}
        (output / 'verification.json').write_text(json.dumps(result, ensure_ascii=False, indent=2))
        print(json.dumps(result, ensure_ascii=False))
        await browser.close()


if __name__ == '__main__':
    asyncio.run(main())
