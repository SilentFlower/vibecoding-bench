"""验证一体化任务工作区的本地流程、隔离与布局。"""
import asyncio
import json
from pathlib import Path
from playwright.async_api import async_playwright, expect


async def main():
    """运行任务模块的离线验收矩阵。@return 无。"""
    out = Path('.deploy/frontend-sidebar-refresh/concept')
    out.mkdir(parents=True, exist_ok=True)
    async with async_playwright() as p:
        browser = await p.chromium.launch()
        page = await browser.new_page(viewport={'width': 1600, 'height': 1100})
        errors, network = [], []
        page.on('pageerror', lambda e: errors.append(str(e)))
        page.on('request', lambda r: network.append(r.url) if r.url.startswith(('http:', 'https:')) else None)
        url = Path('doc/design/flower2api-concept.html').resolve().as_uri()
        await page.goto(url + '#tasks?tab=projects&account=101')
        await page.evaluate('document.fonts.ready')
        await expect(page.locator('iframe')).to_have_count(0)
        await expect(page.locator('[data-work-section]')).to_have_count(6)
        await expect(page.locator('.work-hero')).to_contain_text('补齐状态转换的输入校验')
        await page.locator('[data-work-action="pause"]').click()
        await page.get_by_role('button', name='取消', exact=True).click()
        assert await page.evaluate("workSpaces.get('projects:101').controller_active")
        await page.locator('[data-work-action="pause"]').click()
        await page.locator('[data-work-confirm]').click()
        assert await page.evaluate("!workSpaces.get('projects:101').controller_active&&!workSpaces.get('projects:101').schedule.enabled")
        await page.locator('[data-work-pane="pool"]').first.click()
        await page.locator('[name="instructions"]').fill('测试草稿保留')
        await page.locator('[name="budget_minutes"]').fill('45')
        await page.locator('[data-work-pane="schedule"]').first.click()
        await page.locator('[data-work-pane="pool"]').first.click()
        await expect(page.locator('[name="instructions"]')).to_have_value('测试草稿保留')
        await page.locator('[data-work-pool-search]').fill('tiny')
        await expect(page.locator('[data-work-project]:visible')).to_have_count(1)
        await page.get_by_role('button', name='保存项目池与指南', exact=True).click()
        assert await page.evaluate("workSpaces.get('projects:101').budget_sec===2700")
        await page.locator('[data-work-section="warmup"]').click()
        assert await page.evaluate("workSpaces.get('warmup:101').budget_sec===3600")
        await page.locator('[data-work-pane="schedule"]').first.click()
        await page.locator('[name="interval_minutes"]').fill('300')
        await page.locator('[name="interval_max_minutes"]').fill('100')
        await page.get_by_role('button', name='保存计划', exact=True).click()
        await expect(page.locator('.work-form-error')).to_contain_text('不能小于')
        await page.locator('[name="interval_max_minutes"]').fill('360')
        await page.get_by_role('button', name='保存计划', exact=True).click()
        assert await page.evaluate("workSpaces.get('projects:101').schedule.interval_minutes===60")
        await page.locator('[data-work-pane="model"]').click()
        await page.locator('[name="models"]').fill('测试模型')
        await page.locator('[data-work-discard="model"]').click()
        await expect(page.locator('[name="models"]')).not_to_have_value('测试模型')
        await page.locator('[data-work-section="projects"]').click()
        await page.locator('[data-work-action="cli"]').click()
        dialog = page.locator('#action-dialog')
        await dialog.locator('[name="capture_enabled"]').check()
        await dialog.get_by_role('button', name='保存执行配置').click()
        assert await page.evaluate("workSpaces.get('projects:101').capture_enabled&&!workSpaces.get('warmup:101').capture_enabled")
        await page.locator('[data-work-pane="history"]').click()
        await page.locator('[data-work-delivery="1"]').click()
        await expect(dialog).to_contain_text('已通过独立验收')
        await dialog.locator('[data-work-file]').first.click()
        await expect(dialog.locator('.work-file-preview')).to_be_visible()
        await page.keyboard.press('Escape')
        await page.locator('[data-work-section="topics"]').click()
        await page.locator('[data-work-topic="1"]').click()
        await dialog.locator('[name="title"]').fill('取消的标题')
        await dialog.get_by_role('button', name='取消', exact=True).click()
        await expect(page.locator('#work-list-results')).not_to_contain_text('取消的标题')
        await page.locator('[data-work-topic="1"]').click()
        await dialog.locator('[name="title"]').fill('已编辑的校验任务')
        await dialog.get_by_role('button', name='保存题目', exact=True).click()
        await expect(page.locator('#work-list-results')).to_contain_text('已编辑的校验任务')
        await page.locator('#work-search').fill('质量保障')
        await expect(page.locator('.work-topic')).to_have_count(1)
        await page.locator('#work-search').fill('')
        await page.locator('[data-work-topic-run="1"]').click()
        await dialog.get_by_role('button', name='创建并启动', exact=True).click()
        await expect(page.locator('.work-table')).to_contain_text('批次 #13')
        await page.locator('[data-work-section="runs"]').click()
        await page.locator('[data-work-status="failed"]').click()
        await expect(page.locator('.work-table tbody tr')).to_have_count(1)
        await page.locator('[data-work-run="run-demo-035"]').first.click()
        await expect(dialog).to_contain_text('独立验收失败')
        await dialog.locator('[data-work-detail-tab="files"]').click()
        await dialog.locator('[data-work-file]').first.click()
        await expect(dialog.locator('.work-file-preview')).to_be_visible()
        await page.keyboard.press('Escape')
        await page.locator('[data-work-status="all"]').click()
        await page.locator('[data-work-action="capture-new"]').click()
        await dialog.get_by_role('button', name='启动抓包（示例）', exact=True).click()
        await expect(page.locator('.work-table')).to_contain_text('capture-demo-')
        await page.locator('[data-work-section="accounts"]').click()
        await page.locator('[data-work-action="create"]').click()
        await dialog.locator('[name="name"]').fill('新任务账号')
        await dialog.get_by_role('button', name='进入授权预览', exact=True).click()
        await expect(dialog.locator('[data-work-login-commit]')).to_be_disabled()
        await page.keyboard.press('Escape')
        await expect(page.locator('.work-login-drafts')).to_contain_text('新任务账号')
        await page.locator('[data-work-login-resume="2"]').click()
        await dialog.locator('[data-work-login-simulate]').click()
        await dialog.locator('[data-work-login-commit]').click()
        await expect(page.locator('.work-account-grid')).to_contain_text('新任务账号')
        await expect(page.locator('.work-account-grid .work-account')).to_have_count(4)
        await page.locator('[data-work-account-open="104"][data-work-account-mode="projects"]').click()
        await expect(page.locator('.work-hero')).to_contain_text('请选择项目并保存运行配置')
        await page.locator('[data-work-action="start"]').click()
        assert await page.evaluate("!workSpaces.get('projects:104').controller_active")
        await page.locator('[data-work-section="accounts"]').click()
        await page.locator('[data-work-account-config="101"]').click()
        await dialog.locator('[data-work-quota-policy="101"]').click()
        child = page.locator('dialog.secondary-dialog[open]')
        await child.locator('[name="quota_5h_enabled"]').uncheck()
        await child.get_by_role('button', name='保存额度配置').click()
        assert await page.evaluate("workQuotaPolicies.get(101).warmup_quota_5h_limit_percent===null")
        await page.keyboard.press('Escape')
        # 工作区深链接、非法账号、历史恢复、无隐式启动。
        await page.goto(url + '#tasks?tab=warmup&account=102')
        await expect(page.locator('[name="work_account"]')).to_have_value('102')
        await page.locator('[data-work-section="projects"]').click()
        await page.go_back()
        await expect(page.locator('[data-work-section="warmup"]')).to_have_attribute('aria-current', 'page')
        await page.goto(url + '#tasks?tab=projects&account=999')
        await expect(page.locator('.work-empty')).to_contain_text('请选择运行账号')
        await page.goto(url + '#tasks?tab=projects&account=101')
        for width in [1600, 1280, 720, 390]:
            await page.set_viewport_size({'width': width, 'height': 1000})
            for section in ['projects', 'warmup', 'tasks', 'runs', 'topics', 'accounts']:
                await page.locator('[data-work-section="'+section+'"]').click()
                assert await page.evaluate('document.documentElement.scrollWidth<=innerWidth'), (width, section)
                await page.screenshot(path=str(out / f'work-{section}-{width}.png'), full_page=True)
            await page.locator('[data-work-section="projects"]').click()
            for pane in ['pool', 'schedule', 'model', 'history']:
                await page.locator('[data-work-pane="'+pane+'"]').first.click()
                assert await page.evaluate('document.documentElement.scrollWidth<=innerWidth'), (width, pane)
            await page.locator('[data-work-section="topics"]').click()
            await page.locator('[data-work-topic="1"]').click()
            assert await dialog.evaluate('node=>node.scrollWidth<=node.clientWidth+1'), width
            await page.screenshot(path=str(out / f'work-editor-{width}.png'))
            await page.keyboard.press('Escape')
        assert not errors, errors
        assert not network, network
        result = {'status': 'passed', 'modules': 6, 'viewports': [1600, 1280, 720, 390], 'errors': errors, 'network': network, 'checks': ['暂停取消与确认', '空间隔离', '跨页签草稿', '计划校验', '执行配置', '交付文件', '题目编辑', '批次创建', '运行筛选与详情', '抓包入口', '登录草稿恢复与提交', '额度空值', '深链接及历史', '响应式']}
        (out / 'task-workspace-verification.json').write_text(json.dumps(result, ensure_ascii=False, indent=2))
        print(json.dumps(result, ensure_ascii=False))
        await browser.close()


if __name__ == '__main__':
    asyncio.run(main())
